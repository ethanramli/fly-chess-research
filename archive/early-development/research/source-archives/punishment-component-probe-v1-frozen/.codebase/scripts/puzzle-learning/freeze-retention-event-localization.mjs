import fs from 'node:fs';
import path from 'node:path';
import { sha256 } from '../runtime/fetch-graph.mjs';
const dir='research/data/retention-event-localization-v1';
if(fs.existsSync(dir))throw Error('Frozen output exists');
const p=JSON.parse(fs.readFileSync('research/data/original-puzzle-retention-v1/protocol.json','utf8'));
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const eventPath='research/reports/adaptive-near-transfer-repair-v2-2026-10-07/run/event-informative-0.json';
const event=read(eventPath);
const disabled=read(p.conditions.disabled);
if(JSON.stringify(event.before)!==JSON.stringify(disabled.learned))throw Error('Initial memory mismatch');
fs.mkdirSync(dir,{recursive:true});
const statePath=`${dir}/after-punishment.json`;
fs.writeFileSync(statePath,JSON.stringify({learned:event.after,origin:{path:eventPath,sha256:await sha256(eventPath),field:'after'},scope:'Exact published intermediate learned memory, not an artificial hybrid'},null,2)+'\n');
p.conditions={before:p.conditions.disabled,afterPunishment:statePath,afterReward:p.conditions.informative};
p.purpose='Localize first-puzzle decision-boundary loss across exact saved teaching states.';
p.scope='Read-only development diagnostic of before/punishment/reward snapshots. No new learning, artificial hybrid or transfer claim.';
p.output='research/reports/retention-event-localization-v1-2026-10-07/run';
p.inputs[eventPath]=await sha256(eventPath);p.inputs[statePath]=await sha256(statePath);
p.sources['.codebase/scripts/puzzle-learning/freeze-retention-event-localization.mjs']=await sha256(import.meta.filename);
for(const [file,expected]of Object.entries({...p.inputs,...p.sources}))if(await sha256(file)!==expected)throw Error(`Identity ${file}`);
fs.writeFileSync(`${dir}/protocol.json`,JSON.stringify(p,null,2)+'\n');
const archive='research/source-archives/retention-event-localization-v1-frozen';fs.mkdirSync(archive,{recursive:true});
for(const file of Object.keys(p.sources)){const dest=path.join(archive,file);fs.mkdirSync(path.dirname(dest),{recursive:true});fs.copyFileSync(file,dest,fs.constants.COPYFILE_EXCL);}
fs.copyFileSync(`${dir}/protocol.json`,`${archive}/protocol.json`,fs.constants.COPYFILE_EXCL);
const ap={originalProtocolSha256:await sha256(`${dir}/protocol.json`),originalAuditorPath:'.codebase/scripts/puzzle-learning/audit-near-transfer-repair-transfer.mjs',originalAuditorArchive:`${archive}/.codebase/scripts/puzzle-learning/audit-near-transfer-repair-transfer.mjs`,inputs:{},sources:{}};
const auditor='.codebase/scripts/puzzle-learning/audit-near-transfer-repair-transfer-v2.mjs';ap.sources[auditor]=await sha256(auditor);
fs.writeFileSync(`${dir}/audit-protocol.json`,JSON.stringify(ap,null,2)+'\n');
fs.writeFileSync(`${archive}/manifest.json`,JSON.stringify({protocolSha256:ap.originalProtocolSha256,sources:p.sources,inputs:p.inputs},null,2));
console.log(JSON.stringify({protocolSha256:ap.originalProtocolSha256,conditions:Object.keys(p.conditions)}));
