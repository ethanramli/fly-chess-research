"""Check this proposal's local references and preserve source access hashes; no runs."""
from pathlib import Path
from urllib.parse import unquote
import hashlib
import json
import re

here = Path(__file__).resolve().parent
root = here.parents[2]
documents = [
    here / 'README.md', here / 'sources-and-critical-review.md',
    root / 'documentation/design/research-goals/elife-prospective-protocol-2026-11-02.md',
    root / 'research/journal/discussions/2026-11-02-elife-scope-and-protocol.md',
]
broken, checked, external = [], [], set()
for document in documents:
    body = document.read_text(encoding='utf-8-sig')
    for link in re.findall(r'\]\(([^)]+)\)', body):
        if link.startswith(('http://', 'https://')):
            external.add(link)
            continue
        target = (document.parent / unquote(link.split('#')[0])).resolve()
        # Receipt is generated by this script after link inspection.
        if target == here / 'verification.json':
            continue
        checked.append(str(target.relative_to(root)))
        if not target.exists():
            broken.append({'document': str(document.relative_to(root)), 'target': link})
sources = []
for file in sorted((here / 'source-evidence').glob('*')):
    data = file.read_bytes()
    sources.append({'path': file.name, 'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()})
access = {
    'access_date': '2026-11-02',
    'successful_xml_endpoint': 'https://www.ebi.ac.uk/europepmc/webservices/rest/{PMCID}/fullTextXML',
    'read_scope': 'Selected sections only; see sources-and-critical-review.md',
    'failed_xml': {'PMCID': 'PMC1783616', 'error': 'HTTP 500'},
    'other_failures': ['Nature authentication redirects for Shiu/Lappalainen', 'intermittent PMC CAPTCHA', 'author-hosted episodic PDF timeout', 'FIDE direct fetch timeout'],
    'files': sources,
}
(here / 'source-evidence/access.json').write_text(json.dumps(access, indent=2) + '\n', encoding='utf-8')
receipt = {
    'date': '2026-11-02', 'documents': [str(p.relative_to(root)) for p in documents],
    'local_reference_count': len(checked), 'broken_local_references': broken,
    'external_reference_count': len(external),
    'external_verification': 'Primary retrieval/read coverage and failures recorded in sources ledger; no claim all URLs fetched successfully',
    'scope_checks': {'protocol_is_proposal': 'PROPOSAL' in documents[2].read_text(encoding='utf-8'),
                     'source_ledger_exists': documents[1].exists()},
    'experiments_run': False, 'sealed_data_read': False,
    'simulation_tests': 'Not run: documentation-only task; historical test outcomes cited as reports only',
}
(here / 'verification.json').write_text(json.dumps(receipt, indent=2) + '\n', encoding='utf-8')
print(json.dumps(receipt, indent=2))
if broken:
    raise SystemExit(1)
