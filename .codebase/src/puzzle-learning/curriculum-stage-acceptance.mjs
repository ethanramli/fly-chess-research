// Independent decision gate over records re-derived by the stage auditor.
// This module never runs the learner and never trusts a runner's pass flag.
const HASH=/^[a-f0-9]{64}$/;
const STRATA=['open-defender','blocked-defender','absent-defender','pinned-apparent-defender'];
const CONTROLS=['scratch','absent','shuffled','disabled'];
const BOOTSTRAPS=10_000;
const BOOTSTRAP_SEED=20261011;

function unknown(reason){return {schema:'curriculum-stage-acceptance-v1',status:'unknown',stageAccepted:false,
  unknown:[reason],failed:[],scope:'Decision rule only; caller must independently derive and pin all input observations'};}
function validRows(rows,length,validate){return Array.isArray(rows)&&rows.length===length&&rows.every(validate);}
function count(rows,predicate){return rows.reduce((sum,row)=>sum+(predicate(row)?1:0),0);}
const successful=row=>row.correct&&row.unique&&row.unaided;
const validChoice=row=>typeof row?.trialId==='string'&&typeof row.familyId==='string'
  &&STRATA.includes(row.stratum)&&row.taskCriterion==='capture-retention'
  &&HASH.test(row.positionSha256)&&HASH.test(row.boardHistorySha256)
  &&HASH.test(row.candidateSetSha256)&&HASH.test(row.certificateSha256)
  &&typeof row.correct==='boolean'&&typeof row.unique==='boolean'&&typeof row.unaided==='boolean'
  &&(row.unique?typeof row.selectedAction==='string':row.selectedAction===null);
function familyCounts(rows){const out=new Map();for(const row of rows)out.set(row.familyId,(out.get(row.familyId)??0)+Number(successful(row)));return out;}
function groupSizes(rows,key){const out=new Map();for(const row of rows)out.set(row[key],(out.get(row[key])??0)+1);return out;}
function xorshift(seed){let x=seed>>>0;return ()=>{x^=x<<13;x^=x>>>17;x^=x<<5;return (x>>>0)/0x1_0000_0000;};}

function pairedBootstrapLowerBound(informative,control){
  const byFamily=new Map();
  for(const row of informative){const other=control.get(row.trialId);const current=byFamily.get(row.familyId)??0;
    byFamily.set(row.familyId,current+Number(successful(row))-Number(successful(other)));}
  const families=[...byFamily.keys()].sort(),random=xorshift(BOOTSTRAP_SEED),samples=new Array(BOOTSTRAPS);
  for(let sample=0;sample<BOOTSTRAPS;sample++){
    let delta=0;for(let i=0;i<families.length;i++)delta+=byFamily.get(families[Math.floor(random()*families.length)]);
    samples[sample]=delta;
  }
  samples.sort((a,b)=>a-b);
  return {lower95:samples[Math.floor((BOOTSTRAPS-1)*0.025)],families:families.length,
    resamples:BOOTSTRAPS,seed:BOOTSTRAP_SEED,rng:'xorshift32'};
}

function alignedControl(finalChoices,rows){
  if(!validRows(rows,64,validChoice))return null;
  const map=new Map(rows.map(row=>[row.trialId,row]));
  if(map.size!==64||finalChoices.some(row=>{const other=map.get(row.trialId);
    return !other||other.familyId!==row.familyId||other.stratum!==row.stratum
      ||other.taskCriterion!==row.taskCriterion||other.positionSha256!==row.positionSha256
      ||other.boardHistorySha256!==row.boardHistorySha256||other.candidateSetSha256!==row.candidateSetSha256
      ||other.certificateSha256!==row.certificateSha256;}))return null;
  return map;
}

/**
 * Apply the frozen Stage 1 D1-D8 thresholds to independent audit observations.
 * Inputs must be generated by the separate evaluator from pinned, disjoint data;
 * incomplete evidence returns unknown, while measured shortfalls fail closed.
 */
export function evaluateStage1Acceptance(evidence){
  if(!evidence||typeof evidence!=='object')return unknown('Stage evidence is missing');
  const missing=[];
  const prereq=evidence.prerequisites;
  const requiredPrerequisites=['receiverAccepted','familySplitsDisjoint','sourceCertificatesReplayed',
    'finalSetSealedUntilFreeze','independentStageReplay','memoryContinuityVerified'];
  if(!prereq||requiredPrerequisites.some(key=>typeof prereq[key]!=='boolean'))
    return unknown('Prerequisite audit is incomplete');

  const training=evidence.trainingChoices,validation=evidence.validationChoices;
  const final=evidence.finalChoices,probes=evidence.consequenceProbes,pairs=evidence.counterfactualPairs;
  if(!validRows(training,24,validChoice)||!validRows(validation,16,validChoice)||!validRows(final,64,validChoice))
    return unknown('Training, validation, or final unaided-choice evidence is incomplete');
  if(new Set(training.map(row=>row.trialId)).size!==24||new Set(validation.map(row=>row.trialId)).size!==16
    ||new Set(final.map(row=>row.trialId)).size!==64)return unknown('Choice trial identities are not unique');
  const allTrialIds=[...training,...validation,...final].map(row=>row.trialId);
  if(new Set(allTrialIds).size!==allTrialIds.length)return unknown('Train, validation, and final trial identities overlap');
  const trainFamilies=new Set(training.map(row=>row.familyId)),validationFamilies=new Set(validation.map(row=>row.familyId));
  const finalFamilyIds=new Set(final.map(row=>row.familyId));
  if([...trainFamilies].some(id=>validationFamilies.has(id)||finalFamilyIds.has(id))
    ||[...validationFamilies].some(id=>finalFamilyIds.has(id)))return unknown('Train, validation, and final families overlap');
  if(STRATA.some(stratum=>count(validation,row=>row.stratum===stratum)!==4
    ||count(final,row=>row.stratum===stratum)!==16))return unknown('Validation/final semantic-stratum coverage is incomplete');
  const finalBoards=new Map(final.map(row=>[row.trialId,row]));
  if(!validRows(probes,128,row=>typeof row?.boardId==='string'&&typeof row.actionId==='string'
    &&HASH.test(row.positionSha256)&&HASH.test(row.boardHistorySha256)
    &&Number.isInteger(row.expectedSign)
    &&Math.abs(row.expectedSign)===1&&Number.isInteger(row.predictedSign)&&Math.abs(row.predictedSign)<=1
    &&HASH.test(row.certificateSha256)))return unknown('Certified consequence-probe evidence is incomplete');
  const probeBoards=new Map();for(const row of probes){const actions=probeBoards.get(row.boardId)??new Set();actions.add(row.actionId);probeBoards.set(row.boardId,actions);
    const board=finalBoards.get(row.boardId);if(!board||board.positionSha256!==row.positionSha256
      ||board.boardHistorySha256!==row.boardHistorySha256)return unknown('Probe board/history is not bound to the final evaluation position');}
  if(probeBoards.size!==64||[...probeBoards.values()].some(actions=>actions.size!==2))return unknown('Probe coverage is not two distinct certified actions on each of 64 boards');
  if(!validRows(pairs,32,row=>typeof row?.pairId==='string'&&typeof row.familyId==='string'
    &&validChoice(row.first)&&validChoice(row.second)
    &&row.first.familyId===row.familyId&&row.second.familyId===row.familyId
    &&typeof row.probeOrderingReversed==='boolean'&&HASH.test(row.first.certificateSha256)
    &&HASH.test(row.second.certificateSha256)))return unknown('Counterfactual-pair evidence is incomplete');

  const controls=evidence.controls;if(!controls||CONTROLS.some(name=>!alignedControl(final,controls[name])))
    return unknown('Matched final control choices are incomplete or misaligned');
  const finalFamilies=familyCounts(final);
  const finalFamilySizes=groupSizes(final,'familyId');
  if(pairs.some(row=>!finalFamilies.has(row.familyId))||new Set(pairs.map(row=>row.pairId)).size!==32)
    return unknown('Counterfactual pairs are not uniquely assigned to final relation families');
  const checks={};
  checks.D1=count(training,successful)>=22;
  const validationByStratum=Object.fromEntries(STRATA.map(stratum=>[stratum,
    count(validation,row=>row.stratum===stratum&&successful(row))]));
  checks.D2=count(validation,successful)>=14&&STRATA.every(stratum=>validationByStratum[stratum]>=3);
  const finalByStratum=Object.fromEntries(STRATA.map(stratum=>[stratum,count(final,row=>row.stratum===stratum&&successful(row))]));
  checks.D3=count(final,successful)>=52&&STRATA.every(stratum=>finalByStratum[stratum]>=12)
    &&finalFamilies.size===8&&[...finalFamilySizes.values()].every(size=>size===8)
    &&[...finalFamilies.values()].every(value=>value>=6);
  checks.D4=count(probes,row=>row.predictedSign===row.expectedSign)>=104;
  checks.D5=count(pairs,row=>successful(row.first)&&successful(row.second))>=26
    &&pairs.every(row=>row.probeOrderingReversed);

  const bootstrap={};const advantages={};let causalPass=true;
  for(const name of CONTROLS){const paired=alignedControl(final,controls[name]);
    advantages[name]=count(final,successful)-count(controls[name],successful);
    bootstrap[name]=pairedBootstrapLowerBound(final,paired);
    if(advantages[name]<10||bootstrap[name].lower95<=0)causalPass=false;
  }
  checks.D6=causalPass;

  // Missing retention evidence keeps the stage unknown, but the measured D1-D6
  // and D8 results stay in the report so a stopped campaign has a diagnosis.
  // Researcher decision 2026-10-24 (policy B): Stage 1 has no earlier chess
  // principle to interfere with, so its D7 is deferred to Stage 2's cumulative
  // retention gate, which rechecks Stage 1 validation and sentinels.
  const retention=evidence.retention,unresolved=[];
  const deferred=evidence.retentionDeferral==='stage1-d7-rechecked-by-stage2-v1'?['D7']:[];
  if(!deferred.length&&(!retention||!validRows(retention.validationChoices,16,validChoice)
    ||!Array.isArray(retention.earlierPrinciples)||!Array.isArray(retention.sentinels)))
    unresolved.push(evidence.retentionUnavailable??'Retention challenge evidence is incomplete');
  else if(!deferred.length)checks.D7=count(retention.validationChoices,successful)>=14
    &&retention.earlierPrinciples.every(row=>Number.isInteger(row.before)&&row.before>=0
      &&row.after===row.before&&row.after>=0)
    &&retention.sentinels.every(row=>row?.correct===true)
    &&retention.earlierPrinciples.every(row=>Number.isInteger(row.sentinels)&&row.sentinels===4);

  const state=evidence.stateAudit;
  const stateChecks=['removalLosesAcquiredAdvantage','restoreReproducesIdenticalRankings','fixedIdentitiesUnchanged',
    'certificateAndUpdateReplay','pendingReceiptExactlyOnce','unaidedAndSearchSeparated'];
  if(!state||stateChecks.some(key=>typeof state[key]!=='boolean'))return unknown('State/persistence audit evidence is incomplete');
  checks.D8=stateChecks.every(key=>state[key]===true);

  for(const key of requiredPrerequisites)if(prereq[key]!==true)missing.push(key);
  const failed=Object.entries(checks).filter(([,passed])=>!passed).map(([name])=>name);
  const status=unresolved.length?'unknown':missing.length?'gate-failed':failed.length?'gate-failed':'accepted';
  return {schema:'curriculum-stage-acceptance-v1',status,stageAccepted:status==='accepted',
    prerequisites:{...prereq},checks,failed,missingPrerequisites:missing,unknown:unresolved,deferred,
    metrics:{trainingCorrect:count(training,successful),validationCorrect:count(validation,successful),
      validationByStratum,finalCorrect:count(final,successful),finalByStratum,
      finalByFamily:Object.fromEntries([...finalFamilies.entries()].sort()),
      consequenceSignCorrect:count(probes,row=>row.predictedSign===row.expectedSign),
      counterfactualPairsCorrect:count(pairs,row=>successful(row.first)&&successful(row.second)),
      causalAdvantages:advantages,pairedFamilyBootstrap:bootstrap,
      retentionCorrect:unresolved.length||deferred.length?null:count(retention.validationChoices,successful)},
    scope:'Frozen Stage 1 D1-D8 decision rule over independently derived records; computational evidence only, not general or biological reasoning'};
}

/** Require every predeclared computational replica to pass; no best-seed selection. */
export function evaluateStage1ReplicasAcceptance({replicas,requiredReplicaCount}={}){
  if(!Number.isSafeInteger(requiredReplicaCount)||requiredReplicaCount<1||!Array.isArray(replicas)
    ||replicas.length!==requiredReplicaCount)return unknown('Replica set is missing or does not match the pinned count');
  const reports=replicas.map((evidence,index)=>({replica:index+1,...evaluateStage1Acceptance(evidence)}));
  const unresolved=reports.filter(report=>report.status==='unknown');
  const failed=reports.filter(report=>report.status==='gate-failed');
  const status=unresolved.length?'unknown':failed.length?'gate-failed':'accepted';
  return {schema:'curriculum-stage-replica-acceptance-v1',status,stageAccepted:status==='accepted',
    requiredReplicaCount,acceptedReplicas:reports.filter(report=>report.stageAccepted).length,
    failedReplicas:failed.map(report=>report.replica),unknownReplicas:unresolved.map(report=>report.replica),
    reports,scope:'Every registered computational replica must pass the same frozen Stage 1 D1-D8 gates'};
}

/**
 * Select a training checkpoint using validation only. The input must contain
 * the same 16 disjoint validation trials at every candidate checkpoint. A
 * candidate is eligible only when it passes the frozen D2 count and stratum
 * floors; ties prefer fewer training blocks. Final-set data is not an input.
 */
export function selectStage1ValidationCheckpoint({candidates}={}){
  const unknownResult=reason=>({schema:'stage1-validation-checkpoint-selection-v1',status:'unknown',
    selected:null,reason,scope:'Validation-only selection; no final-family data is accepted by this function'});
  if(!Array.isArray(candidates)||candidates.length<1||candidates.length>33)
    return unknownResult('Candidate checkpoint set is missing or outside the 0..32 block bound');
  const ordered=[...candidates].sort((a,b)=>(a?.blockIndex??-1)-(b?.blockIndex??-1));
  if(ordered.some((row,index)=>!Number.isSafeInteger(row?.blockIndex)||row.blockIndex!==index||row.blockIndex>32
    ||!HASH.test(row?.checkpointSha256??'')||!HASH.test(row?.memorySha256??'')
    ||!validRows(row?.validationChoices,16,validChoice)
    ||new Set(row.validationChoices.map(choice=>choice.trialId)).size!==16
    ||STRATA.some(stratum=>count(row.validationChoices,choice=>choice.stratum===stratum)!==4)))
    return unknownResult('Candidate checkpoint identity or complete validation choices are invalid');
  const reference=ordered[0].validationChoices.map(row=>({trialId:row.trialId,familyId:row.familyId,
    stratum:row.stratum,positionSha256:row.positionSha256,boardHistorySha256:row.boardHistorySha256,
    candidateSetSha256:row.candidateSetSha256,certificateSha256:row.certificateSha256})).sort((a,b)=>a.trialId.localeCompare(b.trialId));
  for(const candidate of ordered){
    const rows=[...candidate.validationChoices].map(row=>({trialId:row.trialId,familyId:row.familyId,
      stratum:row.stratum,positionSha256:row.positionSha256,boardHistorySha256:row.boardHistorySha256,
      candidateSetSha256:row.candidateSetSha256,certificateSha256:row.certificateSha256}))
      .sort((a,b)=>a.trialId.localeCompare(b.trialId));
    if(JSON.stringify(rows)!==JSON.stringify(reference))
      return unknownResult('Validation candidate positions, families or certificates changed across checkpoints');
  }
  const scored=ordered.map(candidate=>{
    const byStratum=Object.fromEntries(STRATA.map(stratum=>[stratum,
      count(candidate.validationChoices,row=>row.stratum===stratum&&successful(row))]));
    const correct=count(candidate.validationChoices,successful);
    return {blockIndex:candidate.blockIndex,checkpointSha256:candidate.checkpointSha256,
      memorySha256:candidate.memorySha256,correct,byStratum,
      eligible:correct>=14&&STRATA.every(stratum=>byStratum[stratum]>=3)};
  });
  const eligible=scored.filter(row=>row.eligible)
    .sort((a,b)=>b.correct-a.correct
      ||Math.min(...Object.values(b.byStratum))-Math.min(...Object.values(a.byStratum))
      ||a.blockIndex-b.blockIndex);
  if(!eligible.length)return {schema:'stage1-validation-checkpoint-selection-v1',status:'gate-failed',
    selected:null,candidates:scored,reason:'No candidate checkpoint passed the frozen Stage 1 D2 validation gates',
    scope:'Validation-only checkpoint selection; final-family data was not read'};
  const selected=eligible[0];
  return {schema:'stage1-validation-checkpoint-selection-v1',status:'selected',selected,
    candidates:scored,criterion:'highest validation correct count, then highest worst-stratum count, then fewest training blocks',
    scope:'Validation-only checkpoint selection; selection must be frozen before final-family access'};
}
