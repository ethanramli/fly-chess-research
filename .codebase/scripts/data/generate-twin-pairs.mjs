// Builds twin-pair candidates from a PGN games file for one restart bucket. Writes only a fresh output folder.
// The eye-input collision check runs when a set is assembled with the real retina; this CLI does not load the retina.
import { createHash } from 'node:crypto';
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { Chess } from 'chess.js';
import { eligibleRestartGame, replayGame, restartSplit } from '../../src/puzzle-learning/twin-pair-generator-v1.mjs';
import { findTwinPairs } from '../../src/puzzle-learning/twin-pair-search-v1.mjs';

const generatorPath = new URL('../../src/puzzle-learning/twin-pair-generator-v1.mjs', import.meta.url);
const searchPath = new URL('../../src/puzzle-learning/twin-pair-search-v1.mjs', import.meta.url);
const KINDS_BY_TASK = { capture: ['recapture'], landing: ['recapture', 'pin'], combined: ['recapture', 'pin', 'value'] };
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const uciOf = move => move.from + move.to + (move.promotion ?? '');

function gameIdOf(pgn) {
  const site = pgn.match(/^\[Site "([^"]*)"\]/m)?.[1]?.replace(/#.*$/, '');
  return site?.split('/').filter(Boolean).pop() ?? '';
}

function main() {
  const { values: args } = parseArgs({ options: {
    games: { type: 'string' }, task: { type: 'string' }, bucket: { type: 'string' }, out: { type: 'string' },
    'old-train-ids': { type: 'string' },
    'max-games': { type: 'string', default: '100' }, 'max-seconds': { type: 'string', default: '3600' },
    'max-pairs-per-game': { type: 'string', default: 'Infinity' },
  } });
  const refuse = message => { console.error(message); process.exitCode = 2; };
  if (!['train', 'development'].includes(args.bucket)) {
    return refuse('Locked test sets are not generated by this command; they need a separately approved sealed-generation step.');
  }
  if (!args.games || !args.out || !Object.hasOwn(KINDS_BY_TASK, args.task)) {
    return refuse('Required: --games FILE --task capture|landing|combined --bucket train|development --out FRESH_DIR');
  }
  const outPath = resolve(args.out);
  if (existsSync(outPath)) return refuse(`Output already exists; use a fresh directory: ${outPath}`);
  const maxGames = Number(args['max-games']), maxSeconds = Number(args['max-seconds']), maxPerGame = Number(args['max-pairs-per-game']);
  if (!(maxGames > 0 && maxSeconds > 0 && maxPerGame > 0)) return refuse('--max-games, --max-seconds and --max-pairs-per-game must be positive numbers');

  // shortcut: reads the whole games file into memory, fine for history batches of a few thousand games; stream it for monthly files.
  const gamesBytes = readFileSync(resolve(args.games));
  const oldTrainIds = new Set(args['old-train-ids']
    ? readFileSync(resolve(args['old-train-ids']), 'utf8').split(/\r?\n/).map(s => s.trim()).filter(Boolean)
    : []);
  const kinds = KINDS_BY_TASK[args.task];
  const games = gamesBytes.toString('utf8').split(/\r?\n\r?\n(?=\[Event )/).filter(chunk => chunk.trim());

  mkdirSync(outPath, { recursive: true });
  const pairsPath = join(outPath, 'pairs.jsonl');
  writeFileSync(pairsPath, '');
  const started = performance.now();
  const skipped = { noSite: 0, ineligible: 0, otherBucket: 0, unreadable: 0 };
  let gamesRead = 0, gamesKept = 0, movesTried = 0, pairCount = 0, stoppedBy = 'end-of-file';

  for (const pgn of games) {
    if (gamesKept >= maxGames) { stoppedBy = 'max-games'; break; }
    if ((performance.now() - started) / 1000 >= maxSeconds) { stoppedBy = 'max-seconds'; break; }
    gamesRead++;
    const id = gameIdOf(pgn);
    if (!id) { skipped.noSite++; continue; }
    if (!eligibleRestartGame(id, oldTrainIds)) { skipped.ineligible++; continue; }
    if (restartSplit(id) !== args.bucket) { skipped.otherBucket++; continue; }
    let entries;
    try {
      entries = replayGame(pgn);
    } catch {
      skipped.unreadable++;
      continue;
    }
    gamesKept++;
    let gamePairs = 0;
    for (const [index, entry] of entries.entries()) {
      if (gamePairs >= maxPerGame) break; // one pair per game keeps pairs from unrelated games, as the eye test requires
      const played = new Chess(entry.fen).moves({ verbose: true }).find(m => uciOf(m) === entry.uci);
      const selected = args.task === 'landing'
        ? Boolean(played && !played.captured && played.piece !== 'k')
        : played?.captured !== undefined;
      if (!selected) continue;
      const result = findTwinPairs({ fen: entry.fen, move: entry.uci, task: args.task, kinds });
      movesTried += result.tried;
      for (const pair of result.pairs) {
        if (gamePairs++ >= maxPerGame) break;
        const record = {
          gameId: id, bucket: args.bucket, ply: entry.ply, history: entries.slice(0, index).map(e => e.uci),
          move: entry.uci, kind: pair.kind, edit: pair.edit, good: pair.good, bad: pair.bad,
        };
        appendFileSync(pairsPath, JSON.stringify(record) + '\n');
        pairCount++;
      }
    }
  }

  const manifest = {
    schema: 'twin-pairs-v1', task: args.task, bucket: args.bucket, gamesRead, gamesKept, skipped, movesTried,
    pairs: pairCount, inputSha256: sha256(gamesBytes), generatorSha256: sha256(readFileSync(generatorPath)),
    searchSha256: sha256(readFileSync(searchPath)), elapsedSeconds: Number(((performance.now() - started) / 1000).toFixed(3)),
    stoppedBy, maxPairsPerGame: maxPerGame,
  };
  writeFileSync(join(outPath, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
}

main();
