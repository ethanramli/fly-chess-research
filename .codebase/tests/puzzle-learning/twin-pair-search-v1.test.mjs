import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { findTwinPairs } from '../../src/puzzle-learning/twin-pair-search-v1.mjs';
import { eligibleRestartGame, restartSplit } from '../../src/puzzle-learning/twin-pair-generator-v1.mjs';

const SCRIPT = fileURLToPath(new URL('../../scripts/data/generate-twin-pairs.mjs', import.meta.url));
const LOCKED_MESSAGE = 'Locked test sets are not generated by this command; they need a separately approved sealed-generation step.';

function findTrainId() {
  for (let i = 0; ; i++) {
    const id = Array.from({ length: 8 }, (_, k) => String.fromCharCode(97 + (Math.floor(i / 26 ** k) % 26))).join('');
    if (eligibleRestartGame(id, new Set()) && restartSplit(id) === 'train') return id;
  }
}

const ID = findTrainId();

test('findTwinPairs finds accepted pin pairs on the pin board', () => {
  const result = findTwinPairs({ fen: '4k3/4b3/8/8/1B6/8/8/4RK2 w - - 0 1', move: 'b4d6', task: 'landing', kinds: ['pin'] });
  assert.ok(result.pairs.length >= 1);
  for (const pair of result.pairs) {
    assert.equal(pair.accepted, true);
    assert.equal(pair.kind, 'pin');
  }
});

test('findTwinPairs finds recapture and value pairs on the combined board', () => {
  const result = findTwinPairs({ fen: '4k3/8/2p5/3p4/8/4N3/8/4K3 w - - 0 1', move: 'e3d5', task: 'combined', kinds: ['recapture', 'value'] });
  assert.ok(result.pairs.some(pair => pair.kind === 'recapture'));
  assert.ok(result.pairs.some(pair => pair.kind === 'value'));
  assert.ok(Number.isInteger(result.tried) && result.tried > 0);
});

test('CLI writes pairs and a manifest for one train bucket', () => {
  const dir = mkdtempSync(join(tmpdir(), 'twin-'));
  try {
    const games = join(dir, 'games.pgn');
    const out = join(dir, 'out');
    writeFileSync(games, `[Event "A"]\n[Site "https://lichess.org/${ID}"]\n\n1. e4 d5 2. exd5 Qxd5 *\n\n[Event "B"]\n\n1. d4 *\n`);
    const run = spawnSync(process.execPath, ['--max-old-space-size=256', SCRIPT, '--games', games, '--task', 'capture', '--bucket', 'train', '--out', out], { encoding: 'utf8' });
    assert.equal(run.status, 0, run.stderr);
    const manifest = JSON.parse(readFileSync(join(out, 'manifest.json'), 'utf8'));
    assert.equal(manifest.gamesRead, 2);
    assert.equal(manifest.gamesKept, 1);
    assert.equal(manifest.skipped.noSite, 1);
    assert.equal(manifest.stoppedBy, 'end-of-file');
    const lines = readFileSync(join(out, 'pairs.jsonl'), 'utf8').split('\n').filter(Boolean);
    assert.ok(lines.length > 0, 'exd5 is defended by the queen, so at least one recapture pair must exist');
    assert.equal(manifest.pairs, lines.length);
    for (const line of lines) {
      const record = JSON.parse(line);
      assert.equal(record.gameId, ID);
      assert.equal(record.kind, 'recapture');
    }
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('CLI refuses locked buckets and existing output folders without writing', () => {
  const dir = mkdtempSync(join(tmpdir(), 'twin-'));
  try {
    const games = join(dir, 'games.pgn');
    writeFileSync(games, '');
    const locked = join(dir, 'locked-out');
    const lockedRun = spawnSync(process.execPath, ['--max-old-space-size=256', SCRIPT, '--games', games, '--task', 'capture', '--bucket', 'locked-a', '--out', locked], { encoding: 'utf8' });
    assert.equal(lockedRun.status, 2);
    assert.ok(lockedRun.stderr.includes(LOCKED_MESSAGE), lockedRun.stderr);
    assert.equal(existsSync(locked), false);

    const existing = join(dir, 'existing');
    mkdirSync(existing);
    const existingRun = spawnSync(process.execPath, ['--max-old-space-size=256', SCRIPT, '--games', games, '--task', 'capture', '--bucket', 'train', '--out', existing], { encoding: 'utf8' });
    assert.equal(existingRun.status, 2);
    assert.deepEqual(readdirSync(existing), []);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
